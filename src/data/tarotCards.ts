// Helper to construct Minor Arcana
function createMinorCards(
  suit: 'wands' | 'cups' | 'swords' | 'pentacles',
  suitName: string,
  elementDesc: string,
  cardsData: {
    name: string;
    num: number;
    upright: string;
    reversed: string;
    keywords: string[];
    desc: string;
  }[]
): TarotCard[] {
  return cardsData.map((c) => {
    const cardData = {
      id: `${suit}-${c.num}`,
      name: `${c.name} of ${suitName}`,
      arcana: 'minor' as const,
      suit,
      number: c.num,
      uprightMeaning: c.upright,
      reversedMeaning: c.reversed,
      keywords: c.keywords,
      description: `${c.desc} (${elementDesc})`,
    };
    return {
      ...cardData,
      imageUrl: getTarotCardImageUrl(cardData),
    };
  });
}

